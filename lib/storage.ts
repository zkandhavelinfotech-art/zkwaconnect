import fs from "node:fs/promises"
import path from "node:path"
import { AwsClient } from "aws4fetch"

// File storage for uploaded and received media.
//  • S3-compatible bucket (Cloudflare R2, Amazon S3, DigitalOcean Spaces, Backblaze B2 …) when S3_BUCKET is set — survives redeploys
//    and works on Vercel / several servers. Needs S3_ENDPOINT, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY (S3_REGION, default "auto").
//  • Otherwise the server's disk: STORAGE_DIR (e.g. a Railway volume mounted at /data), default ./storage.
// Reads fall back to the disk, so files saved before switching to a bucket keep working.

export type Folder = "inbox-media" | "template-media"

const localRoot = () => path.resolve(process.env.STORAGE_DIR || path.join(process.cwd(), "storage"))

export function storageDriver() {
  return process.env.S3_BUCKET && process.env.S3_ENDPOINT && process.env.S3_ACCESS_KEY_ID && process.env.S3_SECRET_ACCESS_KEY ? "s3" as const : "local" as const
}

let client: AwsClient | null = null
function s3() {
  client ??= new AwsClient({ accessKeyId: process.env.S3_ACCESS_KEY_ID!, secretAccessKey: process.env.S3_SECRET_ACCESS_KEY!, service: "s3", region: process.env.S3_REGION || "auto" })
  return client
}
const objectUrl = (folder: Folder, name: string) =>
  `${process.env.S3_ENDPOINT!.replace(/\/+$/, "")}/${encodeURIComponent(process.env.S3_BUCKET!)}/${encodeURIComponent(folder)}/${encodeURIComponent(name)}`

// File names are generated by us; anything with a path in it is refused.
function safeName(name: string) {
  const base = path.basename(name)
  if (!base || base !== name || base.startsWith(".")) throw new Error("Invalid media path")
  return base
}

export async function putFile(folder: Folder, name: string, bytes: Buffer | Uint8Array, mime: string) {
  const file = safeName(name)
  if (storageDriver() === "s3") {
    const response = await s3().fetch(objectUrl(folder, file), { method: "PUT", body: new Uint8Array(bytes), headers: { "Content-Type": mime }, signal: AbortSignal.timeout(120_000) })
    if (!response.ok) throw new Error(`File storage upload failed (${response.status}): ${(await response.text()).slice(0, 200)}`)
    return
  }
  const dir = path.join(localRoot(), folder)
  await fs.mkdir(dir, { recursive: true })
  await fs.writeFile(path.join(dir, file), bytes)
}

export async function getFile(folder: Folder, name: string) {
  const file = safeName(name)
  if (storageDriver() === "s3") {
    const response = await s3().fetch(objectUrl(folder, file), { signal: AbortSignal.timeout(60_000) })
    if (response.ok) return Buffer.from(await response.arrayBuffer())
    if (response.status !== 404) throw new Error(`File storage download failed (${response.status}).`)
  }
  return fs.readFile(path.join(localRoot(), folder, file))
}

// Go-live check: write, read back and delete a small file.
export async function testStorage() {
  const name = `healthcheck-${Date.now()}.txt`
  await putFile("inbox-media", name, Buffer.from("ok"), "text/plain")
  const back = (await getFile("inbox-media", name)).toString()
  if (storageDriver() === "s3") await s3().fetch(objectUrl("inbox-media", name), { method: "DELETE" }).catch(() => null)
  else await fs.unlink(path.join(localRoot(), "inbox-media", name)).catch(() => null)
  if (back !== "ok") throw new Error("Stored file could not be read back.")
  return storageDriver()
}
